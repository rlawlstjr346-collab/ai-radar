const norm = (s: string) => s.trim().toLowerCase();

/** 기사별 용어: 워커 terms + Gemini glossary (같은 단어는 먼저 온 쪽 유지) — 모달 하단 '용어 풀기' 목록과 공유 */
export function itemTerms(item: Pick<FeedItem, "terms" | "glossary">): Term[] {
  const out: Term[] = [];
  const seen = new Set<string>();
  for (const t of [...(item.terms ?? []), ...(item.glossary ?? [])]) {
    const k = norm(t.term);
    if (!k || !t.easy?.trim() || seen.has(k)) continue;
    seen.add(k);
    out.push(t);
  }
  return out;
}

/** 호버 툴팁 매처용: 기사별 용어가 우선, 나머지는 내장 사전으로 채운다 */
export function tooltipTerms(item: Pick<FeedItem, "terms" | "glossary">): Term[] {
  const own = itemTerms(item);
  const seen = new Set(own.map((t) => norm(t.term)));
  return [...own, ...BUILTIN_TERMS.filter((t) => !seen.has(norm(t.term)))];
}
